"""Make the failure analysis inspectable row by row.

The numbers in [failure_analysis.md](../../../docs/families/procurement-allocation/failure_analysis.md)
were first produced by a scratch script, which is a bad place for the definition
of a taxonomy: it cannot be tested, it cannot be regenerated by anyone else, and
one such script was already lost to a temp-directory cleanup. The classifier
lives here instead.

Three views, because checking a conclusion needs different resolutions:

- ``--table`` emits one line per trajectory as CSV, for sorting and filtering.
- ``--worlds`` aggregates by world, which is the unit the panel is scored on.
- ``--episode`` renders a single trajectory as text: the supplier table the buyer
  faced, what it sampled, what those samples showed, what it awarded, and which
  test it failed.

Adequacy is judged against each world's declared binding risk rather than against
yield, because a supplier that is fine on yield can be the wrong choice in a
world where delivery timing or capacity is what bites.
"""

from __future__ import annotations

import argparse
import csv
import io
import json
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any, Iterable, Mapping, Sequence

from .environment import _binomial_defects
from .inference_case_matrix import (
    BUDGET_ACTIONS,
    NOISE_SEED,
    SAMPLE_BATCH,
    build_inference_case_matrix,
)

#: Stages in the order a trajectory passes through them. A row is classified at
#: the first one it fails, so the counts partition rather than overlap.
STAGES = ("solved", "never ran", "no valid action", "no award", "bad award",
          "ignored evidence", "search", "other")

SOLVED_REGRET_USD = 50.0

#: Risks whose deciding attribute is already in the formal offer, so a buyer that
#: quoted a supplier holds the answer without sampling. On-time probability and
#: capacity are both quoted; only yield needs a sample, and even then the sample
#: is noisy. Awarding a supplier that its own quote ruled out is a different
#: failure from not having looked, and the two were merged until an episode was
#: read by hand: a subject sampled the two cheapest suppliers, saw good yield,
#: and awarded them in a world whose binding risk was delivery timing.
VISIBLE_IN_QUOTE = frozenset({"timing", "capacity"})


def adequate(supplier: Mapping[str, Any], risk: str) -> bool:
    """Is this supplier good enough on the dimension this world turns on?"""
    terms = supplier["private_terms"]
    if risk == "timing":
        return float(terms["on_time_probability"]) >= 0.9
    if risk == "capacity":
        return int(terms["capacity"]) >= 20
    return float(terms["quality"]["verified_yield_rate"]) >= 0.95


def observed_yield(supplier: Mapping[str, Any], supplier_id: str) -> float:
    """What the buyer's first sample of this supplier showed, reconstructed.

    Deterministic from the declared noise seed, so this is what the buyer saw
    rather than the hidden truth. Judging a decision against information the
    decider did not hold is how a thin-evidence problem gets mistaken for a
    reasoning failure.
    """
    rate = float(supplier["private_terms"]["quality"]["verified_yield_rate"])
    defects = _binomial_defects(
        seed=NOISE_SEED, supplier_id=supplier_id, draw_index=0,
        sample_size=SAMPLE_BATCH, defect_rate=1.0 - rate)
    return 1.0 - defects / SAMPLE_BATCH


def _world_facts(slug: str) -> tuple[str, str, str]:
    signal, risk = slug.rsplit("__", 1)
    direction = (
        "dear/slow/large is good"
        if signal.endswith("high_is_good") or signal.endswith("long_is_good")
        else "cheap/fast/small is good"
    )
    return signal, risk, direction


def classify(row: Mapping[str, Any], case: Mapping[str, Any]) -> dict[str, Any]:
    """Assign one trajectory to the first stage it fails, with its evidence."""
    slug = str(row["case_id"]).rsplit(".", 1)[-1]
    signal, risk, direction = _world_facts(slug)
    out: dict[str, Any] = {
        "case": slug, "signal": signal, "risk": risk, "direction": direction,
        "seed": row.get("inference_seed"),
        "regret_usd": row.get("regret_to_upper_bound_usd"),
        "verified": 0, "spare_actions": None, "resampled": False, "inquired": False,
        "sampled": "", "awarded": "",
    }
    if row.get("status") != "completed":
        return {**out, "stage": "never ran",
                "mode": str(row.get("failure_condition") or "provider or harness failure")}

    trace = list(row.get("action_trace") or [])
    actions = [a.get("action") for a in trace]
    if "unparseable" in actions:
        return {**out, "stage": "no valid action",
                "mode": "response could not be parsed into an action"}

    suppliers = {str(s["supplier_id"]): s for s in case["payload"]["suppliers"]}
    draws = Counter(
        str(a.get("supplier_id")) for a in trace
        if a.get("action") == "request_sample" and str(a.get("supplier_id")) in suppliers)
    seen = {sid: observed_yield(suppliers[sid], sid) for sid in draws}
    out.update(verified=len(seen), spare_actions=BUDGET_ACTIONS - len(trace),
               resampled=any(v > 1 for v in draws.values()), inquired="inquire" in actions,
               sampled=" ".join(sorted(seen)))

    regret = float(row.get("regret_to_upper_bound_usd") or 0.0)
    if regret < SOLVED_REGRET_USD:
        return {**out, "stage": "solved", "mode": "solved"}

    award = next((a for a in trace if a.get("action") == "submit_award"), None)
    if award is None:
        return {**out, "stage": "no award",
                "mode": "deferred deliberately" if "defer" in actions
                else "budget exhausted before awarding"}

    awarded = {
        sid for line in (award.get("award_lines") or [])
        for sid in suppliers if str(line.get("offer_id", "")) == f"offer_{sid}_v1"}
    out["awarded"] = " ".join(sorted(awarded))

    if any(sid not in seen for sid in awarded):
        return {**out, "stage": "bad award", "mode": "awarded a supplier it never verified"}

    inadequate = [sid for sid in awarded if not adequate(suppliers[sid], risk)]
    if not inadequate:
        return {**out, "stage": "other",
                "mode": "every awarded supplier was adequate yet the award fell short"}

    bad = inadequate[0]
    component = suppliers[bad]["component"]
    if risk in VISIBLE_IN_QUOTE:
        return {**out, "stage": "ignored evidence",
                "mode": f"awarded a supplier its own quote ruled out on {risk}"}
    if any(o != bad and suppliers[o]["component"] == component and adequate(suppliers[o], risk)
           for o in seen):
        return {**out, "stage": "bad award",
                "mode": "verified an adequate supplier and awarded a worse one"}
    if out["spare_actions"] is not None and out["spare_actions"] >= 2:
        return {**out, "stage": "search",
                "mode": "stopped with budget unspent, never checked an adequate supplier"}
    return {**out, "stage": "search",
            "mode": "spent the whole budget without finding an adequate supplier"}


def load_rows(run_root: Path) -> list[dict[str, Any]]:
    return [
        json.loads(path.read_text(encoding="utf-8"))
        for path in sorted(Path(run_root).glob("results/*/seed_*.json"))
    ]


def analyse(run_roots: Mapping[str, Path]) -> list[dict[str, Any]]:
    cases = {c["case_id"].rsplit(".", 1)[-1]: c
             for c in build_inference_case_matrix(surface="labeled")}
    out: list[dict[str, Any]] = []
    for subject, root in run_roots.items():
        for row in load_rows(root):
            slug = str(row["case_id"]).rsplit(".", 1)[-1]
            case = cases.get(slug)
            if case is None:
                continue
            out.append({"subject": subject, **classify(row, case)})
    return out


def to_csv(records: Sequence[Mapping[str, Any]]) -> str:
    if not records:
        return ""
    fields = ["subject", "case", "signal", "direction", "risk", "seed", "stage", "mode",
              "regret_usd", "verified", "spare_actions", "resampled", "inquired",
              "sampled", "awarded"]
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, fieldnames=fields, extrasaction="ignore")
    writer.writeheader()
    for record in records:
        writer.writerow(record)
    return buffer.getvalue()


def world_table(records: Sequence[Mapping[str, Any]]) -> str:
    by = defaultdict(lambda: defaultdict(list))
    for r in records:
        by[r["case"]][r["subject"]].append(r)
    subjects = sorted({r["subject"] for r in records})
    lines = [f"{'world':34s} " + " ".join(f"{s[:16]:>16s}" for s in subjects)]
    for case in sorted(by):
        cells = []
        for s in subjects:
            rs = by[case].get(s, [])
            solved = sum(1 for r in rs if r["stage"] == "solved")
            cells.append(f"{solved}/{len(rs)}" if rs else "-")
        lines.append(f"{case:34s} " + " ".join(f"{c:>16s}" for c in cells))
    return "\n".join(lines)


def render_episode(record: Mapping[str, Any], case: Mapping[str, Any]) -> str:
    """One trajectory as readable text, with the table the buyer actually faced."""
    risk = record["risk"]
    lines = [
        f"{record['subject']}  on  {record['case']}  seed {record['seed']}",
        f"  signal: {record['signal']}   ({record['direction']})",
        f"  binding risk: {risk}",
        f"  verdict: {record['stage']} -- {record['mode']}",
        f"  regret ${record['regret_usd']}   verified {record['verified']} of 8"
        f"   spare actions {record['spare_actions']}",
        "",
        f"  {'supplier':28s} {'price':>7s} {'lead':>5s} {'moq':>4s} {'cap':>4s}"
        f" {'on-time':>8s} {'adequate':>9s} {'sampled':>8s} {'showed':>7s}",
    ]
    sampled = set(str(record["sampled"]).split())
    awarded = set(str(record["awarded"]).split())
    for s in case["payload"]["suppliers"]:
        sid = str(s["supplier_id"]); t = s["private_terms"]
        mark = "AWARDED" if sid in awarded else ("yes" if sid in sampled else "")
        showed = f"{observed_yield(s, sid):.3f}" if sid in sampled else ""
        lines.append(
            f"  {sid:28s} {float(t['base_unit_price_usd']):>7.2f} {int(t['lead_time_days']):>5d}"
            f" {int(t['moq']):>4d} {int(t['capacity']):>4d}"
            f" {float(t['on_time_probability']):>8.2f}"
            f" {('yes' if adequate(s, risk) else 'no'):>9s} {mark:>8s} {showed:>7s}")
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs", type=Path, required=True,
                        help="directory holding inference_v1_* run roots")
    parser.add_argument("--table", action="store_true", help="emit every row as CSV")
    parser.add_argument("--worlds", action="store_true", help="solved counts by world")
    parser.add_argument("--episode", nargs=2, metavar=("CASE", "SEED"))
    parser.add_argument("--subject", help="restrict to one subject")
    arguments = parser.parse_args(argv)

    roots = {p.name.replace("inference_v1_", ""): p
             for p in sorted(Path(arguments.runs).glob("inference_v1_*")) if p.is_dir()}
    roots = {k: v for k, v in roots.items() if (v / "results").is_dir()}
    records = analyse(roots)
    if arguments.subject:
        records = [r for r in records if r["subject"] == arguments.subject]

    if arguments.episode:
        case_slug, seed = arguments.episode
        cases = {c["case_id"].rsplit(".", 1)[-1]: c
                 for c in build_inference_case_matrix(surface="labeled")}
        for r in records:
            if r["case"] == case_slug and str(r["seed"]) == str(seed):
                print(render_episode(r, cases[case_slug]))
                print()
        return 0
    if arguments.worlds:
        print(world_table(records)); return 0
    if arguments.table:
        print(to_csv(records), end=""); return 0

    counts = Counter((r["subject"], r["stage"]) for r in records)
    for subject in sorted({r["subject"] for r in records}):
        total = sum(v for (s, _), v in counts.items() if s == subject)
        print(f"{subject}  ({total} rows)")
        for stage in STAGES:
            n = counts.get((subject, stage), 0)
            if n:
                print(f"   {stage:16s} {n:>3d}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())


__all__ = ["STAGES", "adequate", "analyse", "classify", "observed_yield",
           "render_episode", "to_csv", "world_table"]
