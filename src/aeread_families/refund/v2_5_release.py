"""Portable, provider-free V2.5 release and independent replay setup.

No campaign archives, credentials, paid client initialization or selective retry.
Historical experimental plans are not regenerated by this entrypoint.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import os
from pathlib import Path

from aeread.shared_runner.run.resolver import canonical_json_bytes
from aeread.shared_runner.task.evaluation import audit_family_receipt

from . import v2_5_collection_budget as core
from . import v2_5_seat_design_v3 as v3
from . import v2_5_seat_extension_v4 as v4
from . import v2_5_seat_extension_v5 as v5
from . import v2_5_payment_units_v51 as units

RELEASE_ID = "refund_v25_public_developmental_1"
PANELS = ("core", "policy", "v3_common", "v3_intake", "v3_payments",
          "v3_customer", "v4_payments", "v4_customer", "v5_intake",
          "v51_payments", "v5_customer")
ROLES = core.legacy.ROLES


def build_setup(panel="core", seat="policy", seed=301):
    """Resolve one cohort without loading credentials or making provider calls."""
    if panel not in PANELS or seat not in ROLES:
        raise ValueError("Unknown public panel or active seat")
    if type(seed) is not int or seed < 0:
        raise ValueError("seed must be a nonnegative integer")
    if panel in ("core", "policy"):
        options = dict(include_policy_stress_extension=True,
                       include_policy_frontier_extension=True,
                       include_policy_frontier_hard_extension=True) if panel == "policy" else {}
        return core.build_refund_v25_run(world_seeds=(seed,), active_agents=(seat,), **options)
    version, name = panel.split("_", 1)
    if version == "v3":
        return v3.build_run(cases=v3.build_panels(seed)[name], active_agents=(seat,))
    if version == "v4":
        return v4.build_run(v4.build_panels(seed)[name], active_agents=(seat,))
    name = "payments" if version == "v51" else name
    setup = v5.build_run(v5.build_panels(seed)[name], active_agents=(seat,))
    return units.amend_setup(setup) if version == "v51" else setup


def provider_for(panel):
    if panel in ("core", "policy"):
        return core.legacy.ScriptedV25Provider()
    if panel.startswith("v3_"):
        return v3.ScriptedSeatV3Provider()
    if panel.startswith("v4_"):
        return v4.ScriptedProvider()
    return v5.ScriptedProvider()


def replay_setup(receipt):
    """Factory for aeread verify-replay; root is explicitly supplied by the caller.

    AEREAD_REFUND_V25_RUN_ROOT points to the public entrypoint's fresh output.
    The kernel verifies the reconstructed plan and its pins against the receipt.
    Missing, foreign and changed identities fail closed.
    """
    root = os.environ.get("AEREAD_REFUND_V25_RUN_ROOT")
    if not root:
        raise ValueError("Set AEREAD_REFUND_V25_RUN_ROOT to the public run root")
    contract = json.loads((Path(root) / "release_contract.json").read_bytes())
    if contract.get("release_id") != RELEASE_ID or contract.get("provider") != "scripted":
        raise ValueError("Not a provider-free V2.5 public release contract")
    matches = [row for row in contract["plans"] if row["run_plan_id"] == receipt.get("run_plan_id")]
    if len(matches) != 1:
        raise ValueError("Receipt does not uniquely bind this release contract")
    row = matches[0]
    setup = build_setup(row["panel"], row["seat"], row["seed"])
    if setup.plan.run_plan_id != row["run_plan_id"]:
        raise ValueError("Reconstructed plan differs from the recorded public contract")
    return setup


async def conformance(output: Path, panels=("core",), seats=ROLES, seed=301):
    """Seal and independently audit every scripted trajectory, without paid calls."""
    if output.exists():
        raise FileExistsError("Use a fresh output directory; no restart or top-up")
    if not panels or len(set(panels)) != len(panels) or not seats or len(set(seats)) != len(seats):
        raise ValueError("Nonempty unique panels and seats required")
    plans = [(panel, seat, build_setup(panel, seat, seed)) for panel in panels for seat in seats]
    if len({setup.plan.run_plan_id for _, _, setup in plans}) != len(plans):
        raise ValueError("Public cohort plans must have unique identities")
    output.mkdir(parents=True)
    contract = {"release_id": RELEASE_ID, "provider": "scripted", "paid_calls": 0,
        "inference_status": "provider_free_qualification_not_model_comparison",
        "plans": [{"panel": panel, "seat": seat, "seed": seed,
                   "run_plan_id": setup.plan.run_plan_id}
                  for panel, seat, setup in plans]}
    (output / "release_contract.json").write_bytes(canonical_json_bytes(contract) + b"\n")
    rows = []
    for panel, seat, setup in plans:
        for cell in setup.plan.cells:
            execution = await core.legacy.execute_plan_cell(
                plan=setup.plan, cell_id=cell.cell_id, registry=setup.registry,
                evidence_root=output, prompt_sources=setup.prompt_sources,
                providers={"scripted": provider_for(panel)}, pricing=setup.pricing,
                episode_attempt_ordinal=0, harnesses=setup.harnesses)
            receipt = core.legacy.finalize_family_execution(setup=setup, execution=execution)
            core.legacy.replay_family_receipt(setup=setup, receipt=receipt, evidence_root=output)
            if any(score.primary.value != 1 for score in receipt.scores):
                raise AssertionError(f"Scripted score failed: {panel}/{seat}/{cell.case_id}")
            collaboration = next(s.primary.metadata["collaboration_metrics"] for s in receipt.scores
                if s.leaf.leaf_id == v3.measurement.END_TO_END_LEAF_ID)
            if any(m["value"] != 1 or m["coverage"] != 1 for m in collaboration.values()):
                raise AssertionError(f"Scripted collaboration failed: {panel}/{seat}/{cell.case_id}")
            receipt_path = output / setup.plan.run_plan_id / "tasks" / cell.cell_id / "attempts" / receipt.episode_attempt_id / "evaluation_receipt.json"
            audited = audit_family_receipt(setup=setup, receipt_path=receipt_path)
            rows.append({"panel": panel, "active_seat": seat, "case_id": cell.case_id,
                         "receipt_sha256": audited["receipt_sha256"], "full_score": True,
                         "independent_replay": True})
        print(json.dumps({"panel": panel, "seat": seat, "completed": len(setup.plan.cells)}), flush=True)
    result = {"release_id": RELEASE_ID, "seed": seed, "paid_calls": 0,
              "planned": sum(len(s.plan.cells) for _, _, s in plans),
              "completed": len(rows), "operational_exclusions": 0, "rows": rows}
    (output / "summary.json").write_bytes(canonical_json_bytes(result) + b"\n")
    return result


def main(argv=None):
    parser = argparse.ArgumentParser(description="Provider-free Refund V2.5 qualification")
    parser.add_argument("--panel", choices=("all", *PANELS), default="core")
    parser.add_argument("--active-agents", choices=ROLES, default=None,
                        help="One controlled active seat; omission qualifies all four")
    parser.add_argument("--seed", type=int, default=301)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)
    result = asyncio.run(conformance(args.output,
        panels=PANELS if args.panel == "all" else (args.panel,),
        seats=(args.active_agents,) if args.active_agents else ROLES, seed=args.seed))
    print(json.dumps({k: v for k, v in result.items() if k != "rows"}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
